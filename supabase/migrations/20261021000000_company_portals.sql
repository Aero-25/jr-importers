-- Company portals: a login for the accounts the shop sells to.
--
-- Namib Mills, Logistics Support Services and the rest buy at the weekly dealer
-- price. Today that means an emailed PDF and a phone call. This gives them a
-- login, the same prices the list went out with, and a way to ask for a quote
-- that reaches the shop as a real quote rather than an email somebody has to
-- retype.
--
-- Three things decide the shape of it.
--
-- A portal login is created BY THE SHOP, never by signing up. Email confirmation
-- is switched off on this project, so anybody can register any address; if a
-- portal account could be self-claimed, a stranger would see dealer pricing by
-- typing a customer's address into a signup form. An administrator links a
-- login to a company deliberately.
--
-- A company never sees a cost. The dealer list carries supplier costs, landed
-- costs and margins in the same rows as the price, and row-level security
-- filters rows rather than columns — so the catalogue is served by a function
-- that selects the four fields a buyer may see and cannot return the others.
--
-- A company never sets a price. The quote is priced from the list on the
-- server. What the browser sends is a product and a quantity; everything about
-- money is looked up.

-- ---------------------------------------------------------------------------
-- Who may use a portal
-- ---------------------------------------------------------------------------
create table if not exists public.company_portal_users (
  id            bigint generated by default as identity primary key,
  auth_user_id  uuid not null unique,
  customer_id   uuid not null references public.customers(id) on delete cascade,
  email         text not null,
  active        boolean not null default true,
  invited_by    text,
  last_seen_at  timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists company_portal_users_customer
  on public.company_portal_users (customer_id);

alter table public.company_portal_users enable row level security;

drop policy if exists "admins manage portal logins" on public.company_portal_users;
create policy "admins manage portal logins" on public.company_portal_users
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "a portal user reads their own link" on public.company_portal_users;
create policy "a portal user reads their own link" on public.company_portal_users
  for select to authenticated using (auth_user_id = auth.uid());

grant select, insert, update, delete on public.company_portal_users to authenticated;

drop trigger if exists log_activity_trg on public.company_portal_users;
create trigger log_activity_trg
  after insert or update or delete on public.company_portal_users
  for each row execute function public.log_activity();

-- The company behind the current session, or null for everybody else.
create or replace function private.portal_customer()
returns uuid
language sql
stable
security definer
set search_path to 'public'
as $$
  select u.customer_id
  from public.company_portal_users u
  join public.customers c on c.id = u.customer_id
  where u.auth_user_id = auth.uid()
    and u.active
    and c.active
    and coalesce(c.on_hold, false) = false
  limit 1;
$$;

-- Granted to authenticated, unlike the other private helpers: the quotes
-- policy below calls it, and a row-security expression is evaluated as the
-- querying role rather than as the policy's author. It is SECURITY DEFINER and
-- only ever answers about the caller, so the most it can tell anybody is which
-- company they themselves belong to.
revoke all on function private.portal_customer() from public, anon;
grant execute on function private.portal_customer() to authenticated;

-- ---------------------------------------------------------------------------
-- What a company sees
-- ---------------------------------------------------------------------------
-- The newest list per brand that has gone out or is approved to. Returns only
-- what a buyer may see: a name, a size, availability and the price they will be
-- charged. There is no column here that could carry a cost.
-- Dropped and recreated rather than replaced: the shape of a RETURNS TABLE is
-- part of the signature, so adding item_id cannot be done in place.
drop function if exists public.portal_catalogue();

create function public.portal_catalogue()
returns table (
  -- Keyed on the list line, not the product. Most of the handsets on a dealer
  -- list are not in the shop's own catalogue — they are models the supplier
  -- quotes and the shop brings in — so a product id would leave two thirds of
  -- the list visible but impossible to ask for.
  item_id      bigint,
  product_id   bigint,
  brand        text,
  display_name text,
  storage_gb   integer,
  five_g       boolean,
  price        numeric,
  in_stock     boolean,
  on_hand      integer,
  image        text,
  week_start   date
)
language sql
stable
security definer
set search_path to 'public', 'private'
as $$
  with live as (
    select distinct on (l.brand) l.id, l.brand, l.week_start
    from public.bulk_price_lists l
    where l.status in ('sent', 'approved')
    order by l.brand, l.week_start desc, l.id desc
  )
  select i.id,
         i.product_id,
         live.brand,
         i.display_name,
         i.storage_gb,
         i.five_g,
         i.final_price,
         i.stock_status = 'in_stock',
         i.stock_qty,
         p.image,
         live.week_start
  from live
  join public.bulk_price_list_items i on i.list_id = live.id
  left join public.products p on p.id = i.product_id
  -- Only for a signed-in company. Everybody else gets nothing, which is the
  -- same answer the function gives an anonymous caller.
  where private.portal_customer() is not null
  order by live.brand, i.display_name;
$$;

revoke all on function public.portal_catalogue() from public, anon;
grant execute on function public.portal_catalogue() to authenticated;

-- Who the signed-in portal user is buying for.
create or replace function public.portal_me()
returns jsonb
language sql
stable
security definer
set search_path to 'public', 'private'
as $$
  select case
    when private.portal_customer() is null then jsonb_build_object('ok', false)
    else (
      select jsonb_build_object(
        'ok', true,
        'customer_id', c.id,
        'name', c.name,
        'email', c.email,
        'phone', c.phone,
        'account_code', c.account_code,
        'terms', c.account_terms)
      from public.customers c
      where c.id = private.portal_customer())
  end;
$$;

revoke all on function public.portal_me() from public, anon;
grant execute on function public.portal_me() to authenticated;

-- ---------------------------------------------------------------------------
-- Asking for a quote
-- ---------------------------------------------------------------------------
-- The browser sends a product and a quantity. Every figure is looked up here:
-- a quote priced from what the client posted would be a quote the customer
-- wrote themselves.
create or replace function public.portal_request_quote(
  p_items jsonb,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'private'
as $$
declare
  v_customer uuid := private.portal_customer();
  v_c        public.customers%rowtype;
  v_items    jsonb;
  v_total    numeric;
  v_vat_rate numeric := public.bulk_setting('bulk_sales_vat_rate', '0.15')::numeric;
  v_quote    public.quotes%rowtype;
  v_lines    integer;
begin
  if v_customer is null then
    return jsonb_build_object('ok', false, 'message', 'Sign in with your company account first.');
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    return jsonb_build_object('ok', false, 'message', 'Add something to the request first.');
  end if;

  select * into v_c from public.customers where id = v_customer;

  -- Priced from the live list, never from what was posted.
  select jsonb_agg(
           jsonb_build_object(
             'product_id', cat.product_id,
             'item_id',    cat.item_id,
             'name',       cat.display_name,
             'quantity',   req.qty,
             'price',      cat.price,
             'line_total', round(cat.price * req.qty, 2))
           order by cat.display_name),
         sum(round(cat.price * req.qty, 2)),
         count(*)
    into v_items, v_total, v_lines
  from (
    select (value->>'item_id')::bigint as item_id,
           greatest(coalesce((value->>'quantity')::integer, 0), 0) as qty
    from jsonb_array_elements(p_items)
  ) req
  join public.portal_catalogue() cat on cat.item_id = req.item_id
  where req.qty > 0;

  if coalesce(v_lines, 0) = 0 then
    return jsonb_build_object('ok', false,
      'message', 'None of those are on this week''s list. Refresh and try again.');
  end if;

  insert into public.quotes (
    customer_id, customer_name, customer_email, customer_phone,
    items, subtotal_amount, vat_amount, total_amount,
    status, charge_vat, valid_until, notes, created_by
  )
  values (
    v_c.id, v_c.name, v_c.email, v_c.phone,
    v_items,
    round(v_total / (1 + v_vat_rate), 2),
    v_total - round(v_total / (1 + v_vat_rate), 2),
    v_total,
    'Requested',
    true,
    -- The dealer list is weekly, so a quote off it is good for the week.
    (now() at time zone 'Africa/Windhoek')::date + 7,
    concat_ws(' ', 'Requested through the company portal.', nullif(btrim(coalesce(p_note, '')), '')),
    coalesce(v_c.name, 'Company portal')
  )
  returning * into v_quote;

  return jsonb_build_object(
    'ok', true,
    'quote_id', v_quote.id,
    'quote_number', v_quote.quote_number,
    'lines', v_lines,
    'total', v_quote.total_amount,
    'valid_until', v_quote.valid_until,
    'customer_email', v_c.email,
    'message', format('%s raised for %s.', v_quote.quote_number, v_c.name));
end;
$$;

revoke all on function public.portal_request_quote(jsonb, text) from public, anon;
grant execute on function public.portal_request_quote(jsonb, text) to authenticated;

-- A company's own quotes, and nothing else's.
create or replace function public.portal_my_quotes()
returns table (
  id           bigint,
  quote_number text,
  created_at   timestamptz,
  valid_until  date,
  status       text,
  total_amount numeric,
  items        jsonb
)
language sql
stable
security definer
set search_path to 'public', 'private'
as $$
  select q.id, q.quote_number, q.created_at, q.valid_until, q.status, q.total_amount, q.items
  from public.quotes q
  where private.portal_customer() is not null
    and q.customer_id = private.portal_customer()
  order by q.id desc
  limit 50;
$$;

revoke all on function public.portal_my_quotes() from public, anon;
grant execute on function public.portal_my_quotes() to authenticated;

-- ---------------------------------------------------------------------------
-- Linking a login to a company
-- ---------------------------------------------------------------------------
-- An administrator's job. The auth user must already exist — created in
-- Supabase, or by the person accepting an invitation — and this binds it.
create or replace function public.link_portal_login(p_email text, p_customer_id uuid)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_auth uuid;
  v_name text;
begin
  if not public.is_admin() then
    raise exception 'Only an administrator may give a company a portal login.';
  end if;

  select id into v_auth from auth.users where lower(email) = lower(p_email);
  if v_auth is null then
    return jsonb_build_object('ok', false,
      'message', 'No login exists for that address yet — create the user in Supabase first.');
  end if;

  select name into v_name from public.customers where id = p_customer_id;
  if v_name is null then
    return jsonb_build_object('ok', false, 'message', 'No customer with that id.');
  end if;

  -- A staff login must never double as a company login: is_staff() would let
  -- it read the whole shop while the portal served it dealer pricing.
  if exists (
    select 1 from public.users u
    where u.id = v_auth and lower(u.role) in ('admin','owner','manager','sales','cashier','staff')
  ) then
    return jsonb_build_object('ok', false,
      'message', 'That address is a staff login. Use a separate address for the company portal.');
  end if;

  insert into public.company_portal_users (auth_user_id, customer_id, email, invited_by)
  values (v_auth, p_customer_id, lower(p_email), public.current_actor())
  on conflict (auth_user_id) do update
    set customer_id = excluded.customer_id,
        email       = excluded.email,
        active      = true,
        updated_at  = now();

  return jsonb_build_object('ok', true, 'message', format('%s can now sign in for %s.', p_email, v_name));
end;
$$;

revoke all on function public.link_portal_login(text, uuid) from public, anon;
grant execute on function public.link_portal_login(text, uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- A company may read its own quotes through the table as well
-- ---------------------------------------------------------------------------
drop policy if exists "a company reads its own quotes" on public.quotes;
create policy "a company reads its own quotes" on public.quotes
  for select to authenticated
  using (customer_id is not null and customer_id = private.portal_customer());
