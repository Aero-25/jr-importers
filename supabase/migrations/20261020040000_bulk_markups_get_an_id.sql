-- bulk_variant_markups gets a surrogate id.
--
-- `variant_key` is the natural key and stays unique, but having it as the sole
-- primary key made this the only table in the schema without an `id` column —
-- and `RecordSpec.table` is typed as `TableName`, so the console's generic
-- record editor does `.from(spec.table).select('*').eq('id', …)` against the
-- union of every table. One table without `id` removes it from the shared shape
-- and that call stops compiling, for a screen that has nothing to do with
-- pricing.
--
-- Conforming is the smaller change: the natural key is still enforced, nothing
-- references the old primary key, and an unrelated module keeps working.

alter table public.bulk_variant_markups
  drop constraint if exists bulk_variant_markups_pkey;

alter table public.bulk_variant_markups
  add column if not exists id bigint generated by default as identity;

-- Backfill before the column can be a key.
update public.bulk_variant_markups set id = default where id is null;

alter table public.bulk_variant_markups
  alter column id set not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.bulk_variant_markups'::regclass and contype = 'p'
  ) then
    alter table public.bulk_variant_markups add primary key (id);
  end if;
end
$$;

create unique index if not exists bulk_variant_markups_key
  on public.bulk_variant_markups (variant_key);
